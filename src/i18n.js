export function pathFor(langSlug, slug) {
  return '/' + langSlug + '/' + (slug ? slug + '/' : '');
}

export function matchPath(pathname) {
  const parts = String(pathname).split('/').filter(Boolean);
  if (!parts.length) return null;
  const lang = Object.values(LANGS).find(function (l) { return l.slug === parts[0]; });
  if (!lang) return null;
  const rest = parts.slice(1);
  if (!rest.length) return { lang: lang, structure: STRUCTURES[0] };
  if (rest.length === 1) {
    const s = STRUCTURES.find(function (x) { return x.slug === rest[0]; });
    if (s) return { lang: lang, structure: s };
  }
  return null;
}

